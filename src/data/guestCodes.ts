// Normaliza: saca tildes, espacios y pasa a mayúsculas, para que el código
// funcione sin importar cómo lo tipee cada invitado.
const normalizeCode = (value: string): string =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-zA-Z0-9]/g, "")
    .toUpperCase();

export const validateGuestCode = (code: string): GuestInfo | null => {
  const target = normalizeCode(code);
  const guest = guestCodes.find((g) => normalizeCode(g.code) === target);
  return guest || null;
};
